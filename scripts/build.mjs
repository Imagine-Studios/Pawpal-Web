import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const content = JSON.parse(await readFile(path.join(root, 'content/site.json'), 'utf8'));
const escape = value => String(value).replace(/[&<>"']/g, char => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[char]));
const home = lang => lang === 'es' ? '/es/index.html' : '/';
const image = (name, alt, attributes = '') => `<img src="/assets/images/web-v001/${name}.webp" alt="${escape(alt)}" ${attributes}>`;

function header(lang, legal) {
    const t = content[lang];
    const destination = legal ? 'privacy-policy.html' : 'index.html';
    return `<a class="skip-link" href="#main">${t.skip}</a>
    <header class="site-header"><div class="container header-inner">
      <a class="brand" href="${home(lang)}" aria-label="Oru Studio"><img src="/assets/images/web-v002/oru-wordmark.svg" alt="Oru Studio" width="132" height="60"></a>
      <nav aria-label="${lang === 'es' ? 'Principal' : 'Main'}">${['portfolio','reels','about','contact'].map((id,i) => `<a href="${legal ? home(lang) : ''}#${id}">${t.nav[i]}</a>`).join('')}</nav>
      <div class="languages" aria-label="${lang === 'es' ? 'Idioma' : 'Language'}"><a href="${legal ? '/en/' + destination : '/'}" lang="en" hreflang="en" ${lang === 'en' ? 'aria-current="page"' : ''}>EN</a><span aria-hidden="true">/</span><a href="/es/${destination}" lang="es" hreflang="es" ${lang === 'es' ? 'aria-current="page"' : ''}>ES</a></div>
    </div></header>`;
}

function footer(lang) {
    const t = content[lang];
    return `<footer class="site-footer"><div class="container footer-inner"><p>© ${new Date().getUTCFullYear()} Oru Studio. ${t.rights}</p><div><a href="/${lang}/privacy-policy.html">${t.privacy}</a><a href="${home(lang)}#contact">${t.nav[3]}</a></div></div></footer>`;
}

