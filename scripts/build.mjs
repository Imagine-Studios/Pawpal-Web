function privacy(lang, data) {
    const t = content[lang];
    // Policy HTML is trusted, versioned editorial content, preserved from the existing pages.
    const sections = Object.values(data.sections).map(section => `<section>${section.title ? `<h2>${escape(section.title)}</h2>` : ''}${section.note ? `<p>${escape(section.note)}</p>` : ''}${section.smallNote ? `<p>${section.smallNote}</p>` : ''}${(section.paragraphs || []).map(p => `<p>${p}</p>`).join('')}${section.list ? `<ul>${section.list.map(item => `<li>${item}</li>`).join('')}</ul>` : ''}</section>`).join('');
    return document(lang, `<main id="main" class="container legal section"><a class="text-link" href="${home(lang)}">← ${t.back}</a><h1>${data.title}</h1><p class="caption">${t.updated}: ${escape(data.lastUpdated)}</p><p>${data.note}</p>${sections}</main>`, true);
}

for (const lang of ['en','es']) {
    await writeFile(path.join(root, lang === 'en' ? 'index.html' : 'es/index.html'), landing(lang));
    const policy = JSON.parse(await readFile(path.join(root, `content/privacy-${lang}.json`), 'utf8'));
    await writeFile(path.join(root, `${lang}/privacy-policy.html`), privacy(lang, policy));
}
console.log('Generated ES/EN home and privacy pages. No runtime dependencies.');
